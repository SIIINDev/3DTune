/* The commissioning sequence: bringing a printer from "just assembled" to "prints reliably".
 *
 * Two rules shape this file.
 *
 * First, order matters and the order is not negotiable. Calibrating E-steps on a loose extruder
 * gear, or PID-tuning a hotend whose thermistor is half out of its socket, produces a confident
 * number that describes a broken machine. Mechanics before electronics, electronics before thermal,
 * thermal before anything measured.
 *
 * Second, the client never sends G-code for these steps — it sends a step id and the server looks
 * the commands up here. A "warm it up and move it" button that accepted arbitrary G-code would be a
 * hole straight through the clamps in limits.ts.
 *
 * Steps with no commands are still steps: most of commissioning is done with a hex key and the
 * power off, and pretending otherwise is how guides skip the part that actually matters.
 */

export type CommissioningStage = 'mechanics' | 'sensors' | 'thermal' | 'extruder' | 'bed' | 'finalize';

export type Hazard = 'none' | 'motion' | 'heat';

export type CommissioningStep = {
  id: string;
  stage: CommissioningStage;
  title: string;
  /** Why the step exists. A step whose purpose is unclear gets skipped. */
  why: string;
  /** What to do with your hands. Empty when the step is purely a command. */
  physical?: string;
  /** Prepared commands, run in order. Resolved server-side from this catalogue only. */
  gcode?: string[];
  /** What should happen, so the user can tell success from failure. */
  observe?: string;
  /** The explicit bar for moving on. */
  pass?: string;
  hazard: Hazard;
  /** Needs an explicit confirmation because it moves axes or heats. */
  needsConfirm?: boolean;
  requiresProbe?: boolean;
  /** Points at the dedicated panel that does this properly, instead of duplicating it here. */
  useWizard?: 'pid' | 'esteps' | 'bed' | 'probeOffset' | 'filament';
  /** Honest note when the host cannot do this at all. */
  hostCannot?: string;
};

